def set_cell_shading(cell, color_hex):
    """셀 배경색 설정"""
    shading = cell._element.get_or_add_tcPr()
    shading_elm = shading.makeelement(qn('w:shd'), {
        qn('w:fill'): color_hex,
        qn('w:val'): 'clear'
    })
    shading.append(shading_elm)


def add_heading_styled(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0, 0, 0)
    return h


def add_inventor_table(doc):
    """발명자 테이블"""
    table = doc.add_table(rows=4, cols=5)
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    headers = ['No.', '발명자', '부서', '지분율', '연락처']
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for run in p.runs:
                run.bold = True
                run.font.size = Pt(10)
        set_cell_shading(cell, 'D9E2F3')
    for r in range(1, 4):
        table.rows[r].cells[0].text = str(r)
        for c in range(5):
            for p in table.rows[r].cells[c].paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def add_section(doc, number, title, note, content):
    """표준 섹션 추가"""
    doc.add_paragraph()
    p_title = doc.add_paragraph()
    run = p_title.add_run(f'{number}. {title}')
    run.bold = True
    run.font.size = Pt(13)

    if note:
        p_note = doc.add_paragraph()
        run_note = p_note.add_run(f'※ {note}')
        run_note.font.size = Pt(9)
        run_note.font.color.rgb = RGBColor(100, 100, 100)

    p_content = doc.add_paragraph()
    run_content = p_content.add_run(f'▶ {content}')
    run_content.font.size = Pt(11)


def add_subsection(doc, title, content):
    p_title = doc.add_paragraph()
    run = p_title.add_run(title)
    run.bold = True
    run.font.size = Pt(11)

    p = doc.add_paragraph()
    run = p.add_run(content)
    run.font.size = Pt(11)


def add_impl_method(doc, method_num, title, diagram_desc, detail):
    """구현 방법 섹션"""
    p = doc.add_paragraph()
    run = p.add_run(f'[구현 방법 {method_num}] {title}')
    run.bold = True
    run.font.size = Pt(11)

    p2 = doc.add_paragraph()
    run2 = p2.add_run(f'  도면: {diagram_desc}')
    run2.font.size = Pt(10)
    run2.italic = True

    p3 = doc.add_paragraph()
    run3 = p3.add_run(f'  ▶ {detail}')
    run3.font.size = Pt(11)


def create_doc(filename, title_text, sections, impl_methods, application, effects):
    """직무발명신고서 생성"""
    doc = Document()

    # 스타일
    style = doc.styles['Normal']
    style.font.name = '맑은 고딕'
    style.font.size = Pt(11)
    style._element.rPr.rFonts.set(qn('w:eastAsia'), '맑은 고딕')

    # 제목
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run('발명신고서')
    run.bold = True
    run.font.size = Pt(20)

    doc.add_paragraph()
    add_inventor_table(doc)

    # 1~5번 섹션
    for num, (sec_title, note, content) in sections.items():
        add_section(doc, num, sec_title, note, content)

    # 6번: 구현 방법
    doc.add_paragraph()
    p6 = doc.add_paragraph()
    run6 = p6.add_run('6. 발명 구현 방법의 상세 설명')
    run6.bold = True
    run6.font.size = Pt(13)

    p6_note = doc.add_paragraph()
    run6n = p6_note.add_run('※ 5번 항목에 기술한 발명의 Concept을 구현하기 위한 구체적인 구현 방법 기술')
    run6n.font.size = Pt(9)
    run6n.font.color.rgb = RGBColor(100, 100, 100)

    for m in impl_methods:
        add_impl_method(doc, m['num'], m['title'], m['diagram'], m['detail'])

    # 7번: 적용 실시예
    add_section(doc, 7, '모듈 및 SET 적용 실시예 (Application)',
                '본 발명이 적용되는 재료/부품이 모듈 및 SET에 어떻게 적용되는지 실시예 기술',
                application)

    # 8번: 발명의 효과
    doc.add_paragraph()
    p8 = doc.add_paragraph()
    run8 = p8.add_run('8. 발명의 효과')
    run8.bold = True
    run8.font.size = Pt(13)

    for eff in effects:
        p = doc.add_paragraph(style='List Bullet')
        run = p.add_run(eff)
        run.font.size = Pt(11)

    # 저장
    path = os.path.join(OUTPUT_DIR, filename)
    doc.save(path)
    print(f"  ✓ {filename}")


