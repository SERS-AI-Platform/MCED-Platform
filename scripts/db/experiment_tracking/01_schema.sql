-- =====================================================================
-- 01_schema.sql  —  aecd_platform `experiment` 도메인 (PostgreSQL 15+)
-- 적용 확인: 2026-09-02, 서버 PostgreSQL 15.15 (윈도우 호스트)
-- WHY: 논문 출처 전처리 방법과 그 벤치마크 결과를, 그 결과를 만들어낸
--      임상/측정 데이터 바로 옆에 기록해서 join 한 번으로 추적 가능하게 함.
-- 실행 순서: 최초 한 번만. psql -d aecd_platform -f 01_schema.sql
-- 검증: 적용 후 99_verify.sql의 쿼리를 한 블록씩 실행.
-- 롤백: DROP SCHEMA experiment CASCADE;  (이 도메인만 사라짐)
--
-- master / clinical / measurement 스키마는 CREATE도 ALTER도 하지 않는다.
-- FK로 참조만 한다.
-- =====================================================================

BEGIN;

-- Purpose: prevent accidental execution against another database.
-- Expected result: the script continues only in aecd_platform.
DO $$
BEGIN
    IF current_database() <> 'aecd_platform' THEN
        RAISE EXCEPTION
            'Wrong database: %. Connect to aecd_platform before running this script.',
            current_database();
    END IF;
END
$$;

CREATE SCHEMA IF NOT EXISTS experiment;

-- Purpose: the papers a preprocessing method was taken from.
CREATE TABLE IF NOT EXISTS experiment.papers (
    paper_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    citation TEXT NOT NULL,
    title TEXT,
    doi_or_url TEXT,
    source_tool TEXT,
    notes TEXT,
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT papers_citation_not_blank CHECK (btrim(citation) <> '')
);

-- Purpose: one row per preprocessing method implemented in the SERS-AI codebase.
-- Assumption: method_key equals the dispatch string used in src/sers/preprocessing.py.
CREATE TABLE IF NOT EXISTS experiment.preprocessing_methods (
    method_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_key VARCHAR(128) NOT NULL UNIQUE,
    display_name TEXT,
    stage TEXT NOT NULL,
    paper_id BIGINT REFERENCES experiment.papers(paper_id),
    implementation_path TEXT,
    config_overrides JSONB,
    audit_status TEXT NOT NULL DEFAULT 'pending',
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT methods_key_not_blank CHECK (btrim(method_key) <> ''),
    CONSTRAINT methods_stage_allowed
        CHECK (stage IN ('baseline', 'smoothing', 'normalization', 'combo')),
    CONSTRAINT methods_audit_status_allowed
        CHECK (audit_status IN ('pending', 'approved', 'changes_requested'))
);

-- Purpose: one row per experiment run — this is the general experiment history
-- table, not just preprocessing. The 55 historical entries in
-- logs/experiment_registry.json map onto it 1:1 (method_id NULL), and a
-- preprocessing-lab run is the specialization that also sets method_id and the
-- preprocessing-specific columns below.
-- Assumption: a run is only comparable to another run with the same cohort
-- definition and aggregation, so those are stored explicitly rather than
-- inferred (see docs/ml/EXPERIMENT_CONTEXT.md §7 Comparison Rules).
CREATE TABLE IF NOT EXISTS experiment.runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_name VARCHAR(256) NOT NULL UNIQUE,
    phase VARCHAR(32),
    run_date DATE,
    hypothesis TEXT,
    variable TEXT,
    baseline TEXT,
    cancer_types TEXT[],
    non_cancer_groups TEXT[],
    aggregation TEXT,
    models TEXT[],
    tags TEXT[],
    n_samples INTEGER,
    result_summary TEXT,
    artifacts_dir TEXT,

    -- Preprocessing-lab specific. NULL for a general/historical experiment.
    method_id BIGINT REFERENCES experiment.preprocessing_methods(method_id),
    git_commit VARCHAR(64),
    config_snapshot JSONB,
    data_query_filters JSONB,
    n_subjects INTEGER,
    n_spectra INTEGER,
    qc_passed_n INTEGER,
    qc_failed_n INTEGER,

    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'complete',
    notes TEXT,
    CONSTRAINT runs_name_not_blank CHECK (btrim(run_name) <> ''),
    CONSTRAINT runs_status_allowed CHECK (status IN ('running', 'complete', 'failed')),
    CONSTRAINT runs_counts_non_negative CHECK (
        (n_subjects IS NULL OR n_subjects >= 0)
        AND (n_samples IS NULL OR n_samples >= 0)
        AND (n_spectra IS NULL OR n_spectra >= 0)
        AND (qc_passed_n IS NULL OR qc_passed_n >= 0)
        AND (qc_failed_n IS NULL OR qc_failed_n >= 0)
    )
);

-- Purpose: the exact measurements a run consumed. This is the real foreign key
-- that a cross-database design could not enforce — an experiment can always be
-- traced back to its source clinical records, and a measurement cannot be
-- deleted while an experiment still claims it.
CREATE TABLE IF NOT EXISTS experiment.run_measurements (
    run_id BIGINT NOT NULL REFERENCES experiment.runs(run_id) ON DELETE CASCADE,
    measurement_id BIGINT NOT NULL REFERENCES measurement.measurements(measurement_id),
    PRIMARY KEY (run_id, measurement_id)
);

-- Purpose: long-format metrics so new metric names need no schema change.
CREATE TABLE IF NOT EXISTS experiment.run_metrics (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES experiment.runs(run_id) ON DELETE CASCADE,
    metric_name VARCHAR(128) NOT NULL,
    metric_value DOUBLE PRECISION,
    split TEXT,
    model_name VARCHAR(128),
    CONSTRAINT metrics_name_not_blank CHECK (btrim(metric_name) <> ''),
    CONSTRAINT metrics_split_allowed
        CHECK (split IS NULL OR split IN ('train', 'val', 'test', 'oof')),
    -- NULLS NOT DISTINCT (PostgreSQL 15+, 확인된 서버 15.15): split and model_name are nullable, and
    -- without this a re-run would insert duplicates instead of updating, because
    -- NULLs default to being distinct from each other in a unique constraint.
    CONSTRAINT metrics_unique_per_run
        UNIQUE NULLS NOT DISTINCT (run_id, metric_name, split, model_name)
);

-- Purpose: accelerate the joins the comparison workflow actually runs.
CREATE INDEX IF NOT EXISTS methods_paper_idx
    ON experiment.preprocessing_methods(paper_id);
CREATE INDEX IF NOT EXISTS runs_method_idx
    ON experiment.runs(method_id);
CREATE INDEX IF NOT EXISTS runs_phase_idx
    ON experiment.runs(phase);
CREATE INDEX IF NOT EXISTS run_measurements_measurement_idx
    ON experiment.run_measurements(measurement_id);
CREATE INDEX IF NOT EXISTS run_metrics_run_idx
    ON experiment.run_metrics(run_id);

COMMIT;
